"""Bakes ui/index.html (with the Inter font inlined) into src/ui_html.h as a byte array.
Run after editing the UI:  python tools/gen_ui.py
(A byte array is used because MSVC cannot hold string literals over 64 KB.)"""
import base64
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
html = open(os.path.join(root, "ui", "index.html"), encoding="utf-8").read()
font = base64.b64encode(open(os.path.join(root, "ui", "inter.woff2"), "rb").read()).decode()
html = html.replace("url('inter.woff2')", "url(data:font/woff2;base64," + font + ")")
assert "data:font/woff2" in html, "font placeholder not found"
data = html.encode("utf-8")

lines = []
for i in range(0, len(data), 24):
    lines.append(",".join(str(b) for b in data[i:i + 24]))
out = ("// Generated by tools/gen_ui.py - do not edit by hand\n#pragma once\n"
       f"static const unsigned char UI_HTML[{len(data)}] = {{\n" + ",\n".join(lines) + "\n};\n")
open(os.path.join(root, "src", "ui_html.h"), "w", encoding="utf-8").write(out)
print(f"src/ui_html.h written ({len(data)} bytes)")
